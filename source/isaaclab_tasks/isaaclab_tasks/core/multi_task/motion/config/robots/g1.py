def g1_reference_kinematics(env):
    """Build the hash-verified external BFM reference model on the environment device."""
    from ....kinematics import NewtonKinematics, NewtonKinematicsCfg

    root = Path(env.cfg.commands.motion.task_table.reference_artifact_root).expanduser()
    path = root / _G1_REFERENCE_MJCF_RELATIVE_PATH
    if not path.is_file():
        raise FileNotFoundError(f"G1 reference MJCF does not exist: {path}")
    with path.open("rb") as stream:
        actual = hashlib.file_digest(stream, "sha256").hexdigest()
    if actual != _G1_MJCF_SHA256:
        raise ValueError(f"G1 reference MJCF hash differs: expected {_G1_MJCF_SHA256}, got {actual}.")
    return NewtonKinematics(
        NewtonKinematicsCfg(
            usd_path=None,
            mjcf_path=str(path),
            device=str(env.device),
            collapse_fixed_joints=False,
        )
    )


