def _by_joint(values: tuple[float, ...]) -> dict[str, float]:
    """Map behavior-order controller values to exact physical joint names."""
    float32_values = np.asarray(values, dtype=np.float32).tolist()
    return dict(zip(G1_BEHAVIOR_JOINT_NAMES, float32_values, strict=True))


